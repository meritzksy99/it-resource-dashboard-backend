-- 이슈관리(화면 오류) 신규 테이블. 19c 호환 DDL만 사용.
CREATE TABLE DASH_ISSUE (
    ISSUE_ID     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    SCRN_ID      VARCHAR2(100)  NOT NULL,            -- 화면ID
    REG_EMPNO    VARCHAR2(30)   NOT NULL,            -- 작성자 사번
    ERR_CNTT     VARCHAR2(2000) NOT NULL,            -- 오류설명
    FILE_NM      VARCHAR2(255),                      -- 첨부 파일명
    FILE_CTYPE   VARCHAR2(100),                      -- 첨부 Content-Type
    FILE_DATA    BLOB,                               -- 스크린샷 원본
    STAT_CD      VARCHAR2(20) DEFAULT 'OPEN' NOT NULL,
    PRIR_CD      VARCHAR2(20) DEFAULT 'MEDIUM' NOT NULL,
    RSLV_CNTT    VARCHAR2(2000),                     -- 해결내용
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(30),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   VARCHAR2(30),
    CONSTRAINT PK_DASH_ISSUE PRIMARY KEY (ISSUE_ID),
    CONSTRAINT CK_DASH_ISSUE_STAT CHECK (STAT_CD IN ('OPEN','IN_PROGRESS','RESOLVED','CLOSED')),
    CONSTRAINT CK_DASH_ISSUE_PRIR CHECK (PRIR_CD IN ('LOW','MEDIUM','HIGH','CRITICAL'))
);
CREATE INDEX IX_DASH_ISSUE_STAT ON DASH_ISSUE (STAT_CD);

CREATE TABLE DASH_ISSUE_CMT (
    CMT_ID       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ISSUE_ID     NUMBER         NOT NULL,
    REG_EMPNO    VARCHAR2(30)   NOT NULL,
    CMT_CNTT     VARCHAR2(2000) NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY   VARCHAR2(30),
    UPDATED_AT   TIMESTAMP,
    UPDATED_BY   VARCHAR2(30),
    CONSTRAINT PK_DASH_ISSUE_CMT PRIMARY KEY (CMT_ID),
    CONSTRAINT FK_DASH_ISSUE_CMT_DASH_ISSUE FOREIGN KEY (ISSUE_ID)
        REFERENCES DASH_ISSUE (ISSUE_ID) ON DELETE CASCADE
);
CREATE INDEX IX_DASH_ISSUE_CMT_ISSUE ON DASH_ISSUE_CMT (ISSUE_ID);
