-- 주간보고: 개인 보고(DASH_WKLY_RPT) + 파트 취합본(DASH_WKLY_SUM). 19c 호환 DDL만 사용.
CREATE TABLE DASH_WKLY_RPT (
    RPT_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    WEEK_YMD      VARCHAR2(8)    NOT NULL,          -- 주 시작(월) YYYYMMDD
    SR_NO         VARCHAR2(30)   NOT NULL,          -- 기간계 SR번호
    SR_TITL       VARCHAR2(500),                    -- SR 제목 스냅샷(TITL_CNTT)
    REG_EMPNO     VARCHAR2(30)   NOT NULL,          -- 작성자
    DEPT_CD       VARCHAR2(20),                     -- 작성 시점 소속 스냅샷
    PART_CD       VARCHAR2(20),
    RPT_CNTT      VARCHAR2(2000) NOT NULL,          -- 개인 의견/내용
    PLAN_DATE     VARCHAR2(8)    NOT NULL,          -- 개인이 적은 반영예정일 YYYYMMDD
    SR_PLAN_DATE  VARCHAR2(8),                      -- SR 반영예정일(RFLC_SCDL_DATE) 스냅샷
    DELAY_RSN     VARCHAR2(1000),                   -- 지연사유
    LEADER_CMT    VARCHAR2(1000),                   -- 업무리더 추가의견
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY    VARCHAR2(30),
    UPDATED_AT    TIMESTAMP,
    UPDATED_BY    VARCHAR2(30),
    CONSTRAINT PK_DASH_WKLY_RPT PRIMARY KEY (RPT_ID),
    CONSTRAINT UK_DASH_WKLY_RPT_WK_SR_EMP UNIQUE (WEEK_YMD, SR_NO, REG_EMPNO)
);
CREATE INDEX IX_DASH_WKLY_RPT_WEEK ON DASH_WKLY_RPT (WEEK_YMD);

CREATE TABLE DASH_WKLY_SUM (
    SUM_ID        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    WEEK_YMD      VARCHAR2(8)    NOT NULL,
    DEPT_CD       VARCHAR2(20)   NOT NULL,
    PART_CD       VARCHAR2(20)   NOT NULL,
    SUM_CNTT      VARCHAR2(4000) NOT NULL,          -- 파트 취합 최종본
    REG_EMPNO     VARCHAR2(30)   NOT NULL,          -- 제출한 업무리더
    TEAM_CMT      VARCHAR2(1000),                   -- 팀장 최종의견
    TEAM_CMT_EMPNO VARCHAR2(30),
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CREATED_BY    VARCHAR2(30),
    UPDATED_AT    TIMESTAMP,
    UPDATED_BY    VARCHAR2(30),
    CONSTRAINT PK_DASH_WKLY_SUM PRIMARY KEY (SUM_ID),
    CONSTRAINT UK_DASH_WKLY_SUM_WK_PART UNIQUE (WEEK_YMD, DEPT_CD, PART_CD)
);
